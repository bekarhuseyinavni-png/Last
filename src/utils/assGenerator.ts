import { AssStyleDefinition, SubtitleCue, SubtitleHorizontalAlign, SubtitleStyle, SubtitleVerticalAlign } from '../types';
import { htmlToAss } from './htmlSubtitleParser';

export function formatAssTimestamp(ms: number): string {
  const totalSeconds = Math.floor(ms / 1000);
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;
  const centiseconds = Math.floor((ms % 1000) / 10);
  return `${hours}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}.${String(centiseconds).padStart(2, '0')}`;
}

export function getAssAlignment(vAlign: SubtitleVerticalAlign, hAlign: SubtitleHorizontalAlign): number {
  if (vAlign === 'TOP') {
    if (hAlign === 'LEFT') return 7;
    if (hAlign === 'RIGHT') return 9;
    return 8;
  }
  if (vAlign === 'MIDDLE') {
    if (hAlign === 'LEFT') return 4;
    if (hAlign === 'RIGHT') return 6;
    return 5;
  }
  // BOTTOM
  if (hAlign === 'LEFT') return 1;
  if (hAlign === 'RIGHT') return 3;
  return 2;
}

export function hexColorToAssHex(colorStr: string): string {
  if (!colorStr) return '&H00FFFFFF';
  if (colorStr.startsWith('rgba') || colorStr.startsWith('rgb')) {
    const nums = colorStr.match(/\d+(\.\d+)?/g);
    if (nums && nums.length >= 3) {
      const r = parseInt(nums[0], 10);
      const g = parseInt(nums[1], 10);
      const b = parseInt(nums[2], 10);
      const aFloat = nums[3] !== undefined ? parseFloat(nums[3]) : 1.0;
      const assAlpha = Math.round((1 - aFloat) * 255);
      return `&H${assAlpha.toString(16).padStart(2, '0').toUpperCase()}${b.toString(16).padStart(2, '0').toUpperCase()}${g.toString(16).padStart(2, '0').toUpperCase()}${r.toString(16).padStart(2, '0').toUpperCase()}`;
    }
  }

  const clean = colorStr.replace('#', '').trim();
  if (clean.length === 8) {
    const a = parseInt(clean.substring(0, 2), 16);
    const r = clean.substring(2, 4);
    const g = clean.substring(4, 6);
    const b = clean.substring(6, 8);
    const assAlpha = 255 - a;
    return `&H${assAlpha.toString(16).padStart(2, '0').toUpperCase()}${b.toUpperCase()}${g.toUpperCase()}${r.toUpperCase()}`;
  }
  if (clean.length === 6) {
    const r = clean.substring(0, 2);
    const g = clean.substring(2, 4);
    const b = clean.substring(4, 6);
    return `&H00${b.toUpperCase()}${g.toUpperCase()}${r.toUpperCase()}`;
  }
  return '&H00FFFFFF';
}

export function generateAss(
  title: string,
  subtitles: SubtitleCue[],
  style: SubtitleStyle,
  applyTimeOffset: boolean = false,
  videoWidth: number = 1920,
  videoHeight: number = 1080,
  additionalStyles: string[] = [],
  introOffsetMs: number = 0,
  styleDefinitions?: AssStyleDefinition[]
): string {
  const playResX = videoWidth > 0 ? videoWidth : 1920;
  const playResY = videoHeight > 0 ? videoHeight : 1080;

  const lines: string[] = [];

  // [Script Info]
  lines.push('[Script Info]');
  lines.push('; Script generated by remsubs playground');
  lines.push('; Unified PlayRes coordinate system (1:1 with video frames)');
  lines.push(`Title: ${title || 'remsubs_altyazi.ass'}`);
  lines.push('ScriptType: v4.00+');
  lines.push('WrapStyle: 0');
  lines.push('ScaledBorderAndShadow: yes');
  lines.push(`PlayResX: ${playResX}`);
  lines.push(`PlayResY: ${playResY}`);
  lines.push('');

  // [V4+ Styles]
  lines.push('[V4+ Styles]');
  lines.push('Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding');

  const declaredStyleNames = new Set<string>();

  if (styleDefinitions && styleDefinitions.length > 0) {
    for (const def of styleDefinitions) {
      const sName = def.name.trim() || 'Default';
      const fName = def.fontName || 'Arial';
      const fSize = Math.round(def.fontSize || 48);
      const priCol = hexColorToAssHex(def.primaryColor || '#FFFFFF');
      const secCol = def.secondaryColor ? hexColorToAssHex(def.secondaryColor) : '&H000000FF';
      const outCol = hexColorToAssHex(def.outlineColor || '#000000');
      const bakCol = hexColorToAssHex(def.backColor || 'rgba(0,0,0,0.6)');
      const bld = def.bold ? -1 : 0;
      const itl = def.italic ? -1 : 0;
      const und = def.underline ? -1 : 0;
      const strk = def.strikeOut ? -1 : 0;
      const scX = def.scaleX || 100;
      const scY = def.scaleY || 100;
      const spc = def.spacing || 0;
      const ang = def.angle || 0;
      const bStyle = def.borderStyle || 1;
      const outW = def.outline ?? 2.5;
      const shd = def.shadow ?? 2;
      const align = def.alignment || 2;
      const mL = def.marginL || 20;
      const mR = def.marginR || 20;
      const mV = def.marginV || 40;

      lines.push(`Style: ${sName},${fName},${fSize},${priCol},${secCol},${outCol},${bakCol},${bld},${itl},${und},${strk},${scX},${scY},${spc},${ang},${bStyle},${outW},${shd},${align},${mL},${mR},${mV},1`);
      declaredStyleNames.add(sName.toLowerCase());
    }
  } else {
    const fontName = style.fontName?.trim() || 'Arial';
    const fontSize = Math.round(Math.max(10, Math.min(300, style.fontSizeSp)));
    const primaryColour = hexColorToAssHex(style.textColor);
    const secondaryColour = '&H000000FF';
    const outlineColour = hexColorToAssHex(style.outlineColor);
    const backColour = hexColorToAssHex(style.backgroundColor);
    const bold = style.isBold ? -1 : 0;
    const italic = style.isItalic ? -1 : 0;
    const underline = style.isUnderline ? -1 : 0;
    const borderStyle = style.hasBackgroundBox ? 3 : 1;
    const outlineWidth = style.hasOutline ? Math.max(1, Math.round(style.outlineWidth)) : 0;
    const shadowDepth = style.hasOutline ? 2 : 0;
    const alignment = getAssAlignment(style.verticalAlign, style.horizontalAlign);
    const marginL = Math.max(10, Math.round(style.horizontalPaddingDp));
    const marginR = Math.max(10, Math.round(style.horizontalPaddingDp));
    const marginV = Math.max(10, Math.round(style.verticalOffsetDp));
    const ang = style.angle || 0;

    lines.push(`Style: Default,${fontName},${fontSize},${primaryColour},${secondaryColour},${outlineColour},${backColour},${bold},${italic},${underline},0,100,100,0,${ang},${borderStyle},${outlineWidth},${shadowDepth},${alignment},${marginL},${marginR},${marginV},1`);
    declaredStyleNames.add('default');
  }

  // Include any extra styles from additionalStyles if not yet declared
  for (const extraStyleLine of additionalStyles) {
    const trimmed = extraStyleLine.trim();
    if (trimmed.toLowerCase().startsWith('style:')) {
      const parts = trimmed.substring(6).trim().split(',');
      if (parts.length > 0) {
        const sName = parts[0].trim().toLowerCase();
        if (sName && !declaredStyleNames.has(sName)) {
          lines.push(trimmed);
          declaredStyleNames.add(sName);
        }
      }
    }
  }

  // Ensure every cue with a distinct styleName is declared
  const fallbackFont = style.fontName?.trim() || 'Arial';
  const fallbackSize = Math.round(Math.max(10, Math.min(300, style.fontSizeSp)));
  const fallbackPri = hexColorToAssHex(style.textColor);
  const fallbackOut = hexColorToAssHex(style.outlineColor);
  const fallbackBak = hexColorToAssHex(style.backgroundColor);

  for (const cue of subtitles) {
    const sName = cue.styleName?.trim();
    if (sName && !declaredStyleNames.has(sName.toLowerCase())) {
      lines.push(`Style: ${sName},${fallbackFont},${fallbackSize},${fallbackPri},&H000000FF,${fallbackOut},${fallbackBak},${style.isBold ? -1 : 0},${style.isItalic ? -1 : 0},${style.isUnderline ? -1 : 0},0,100,100,0,0,1,2,2,2,20,20,40,1`);
      declaredStyleNames.add(sName.toLowerCase());
    }
  }

  lines.push('');

  // [Events]
  lines.push('[Events]');
  lines.push('Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');

  const totalOffset = (applyTimeOffset ? style.timeOffsetMs : 0) + introOffsetMs;

  const sortedCues = [...subtitles].sort((a, b) => a.startTimeMs - b.startTimeMs);
  for (const cue of sortedCues) {
    const startMs = Math.max(0, cue.startTimeMs + totalOffset);
    const endMs = Math.max(startMs, cue.endTimeMs + totalOffset);
    const startStr = formatAssTimestamp(startMs);
    const endStr = formatAssTimestamp(endMs);

    const formattedText = formatCueTextForAss(cue);
    const layer = cue.layer || 0;
    const styleName = cue.styleName?.trim() || 'Default';
    const actor = cue.actor || '';
    const marginVVal = cue.marginV || 0;
    const marginLVal = cue.marginL || 0;
    const marginRVal = cue.marginR || 0;
    const effectVal = cue.effect || '';

    lines.push(`Dialogue: ${layer},${startStr},${endStr},${styleName},${actor},${marginLVal},${marginRVal},${marginVVal},${effectVal},${formattedText}`);
  }

  return lines.join('\n') + '\n';
}

function formatCueTextForAss(cue: SubtitleCue): string {
  const rawOrClean = cue.rawText?.trim() ? cue.rawText : cue.cleanText;
  const baseText = htmlToAss(rawOrClean).replace(/\r\n/g, '\\N').replace(/\n/g, '\\N');

  if (!cue.customPositionEnabled && cue.customAngle === undefined && cue.customAngle === null) {
    return baseText;
  }

  const tags: string[] = [];
  if (cue.customPositionEnabled) {
    if (cue.customVerticalAlign && cue.customHorizontalAlign) {
      const customAlign = getAssAlignment(cue.customVerticalAlign, cue.customHorizontalAlign);
      tags.push(`\\an${customAlign}`);
    }

    if (cue.customFontSizeSp) {
      tags.push(`\\fs${Math.round(cue.customFontSizeSp)}`);
    }

    if (cue.customTextColorArgb) {
      const argb = cue.customTextColorArgb;
      const red = (argb >> 16) & 0xff;
      const green = (argb >> 8) & 0xff;
      const blue = argb & 0xff;
      tags.push(`\\c&H${blue.toString(16).padStart(2, '0').toUpperCase()}${green.toString(16).padStart(2, '0').toUpperCase()}${red.toString(16).padStart(2, '0').toUpperCase()}&`);
    }

    if (cue.customOutlineColorArgb) {
      const argb = cue.customOutlineColorArgb;
      const red = (argb >> 16) & 0xff;
      const green = (argb >> 8) & 0xff;
      const blue = argb & 0xff;
      tags.push(`\\3c&H${blue.toString(16).padStart(2, '0').toUpperCase()}${green.toString(16).padStart(2, '0').toUpperCase()}${red.toString(16).padStart(2, '0').toUpperCase()}&`);
    }

    if (cue.customIsItalic !== null && cue.customIsItalic !== undefined) {
      tags.push(cue.customIsItalic ? '\\i1' : '\\i0');
    }
    if (cue.customIsBold !== null && cue.customIsBold !== undefined) {
      tags.push(cue.customIsBold ? '\\b1' : '\\b0');
    }
    if (cue.customIsUnderline !== null && cue.customIsUnderline !== undefined) {
      tags.push(cue.customIsUnderline ? '\\u1' : '\\u0');
    }
  }

  if (cue.customAngle !== undefined && cue.customAngle !== null && !baseText.includes('\\frz')) {
    tags.push(`\\frz${Math.round(cue.customAngle)}`);
  }

  if (tags.length > 0) {
    return `{${tags.join('')}}${baseText}`;
  }
  return baseText;
}

export function rebuildAssPreservingOriginalStructure(
  originalAss: string,
  updatedCues: SubtitleCue[]
): string {
  const lines = originalAss.split(/\r?\n/);
  const headerLines: string[] = [];
  let foundEvents = false;
  let formatFound = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.toLowerCase().startsWith('[events]')) {
      foundEvents = true;
      headerLines.push('[Events]');
      continue;
    }
    if (foundEvents) {
      if (trimmed.toLowerCase().startsWith('format:')) {
        formatFound = true;
        headerLines.push(trimmed);
        break;
      }
    } else {
      headerLines.push(line);
    }
  }

  if (!foundEvents) {
    return generateAss('remsubs_export.ass', updatedCues, {
      fontName: 'Arial',
      fontSizeSp: 48,
      isBold: true,
      isItalic: false,
      isUnderline: false,
      textColor: '#FFFFFF',
      outlineColor: '#000000',
      hasOutline: true,
      outlineWidth: 2.5,
      hasBackgroundBox: false,
      backgroundColor: '#00000099',
      verticalAlign: 'BOTTOM',
      horizontalAlign: 'CENTER',
      verticalOffsetDp: 32,
      horizontalPaddingDp: 16,
      timeOffsetMs: 0,
    });
  }

  if (!formatFound) {
    headerLines.push('Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');
  }

  const sortedCues = [...updatedCues].sort((a, b) => a.startTimeMs - b.startTimeMs);
  for (const cue of sortedCues) {
    const startStr = formatAssTimestamp(cue.startTimeMs);
    const endStr = formatAssTimestamp(cue.endTimeMs);
    const styleName = cue.styleName || 'Default';
    const actor = cue.actor || '';
    const layer = cue.layer || 0;
    const marginL = cue.marginL || 0;
    const marginR = cue.marginR || 0;
    const marginV = cue.marginV || 0;
    const effect = cue.effect || '';
    const formattedText = formatCueTextForAss(cue);

    headerLines.push(`Dialogue: ${layer},${startStr},${endStr},${styleName},${actor},${marginL},${marginR},${marginV},${effect},${formattedText}`);
  }

  return headerLines.join('\n') + '\n';
}
